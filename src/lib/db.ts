type GlobalWithPool = typeof globalThis & {
  __deixaAquiPool?: Pool;
  __deixaAquiReady?: Promise<void>;
  __deixaAquiDb?: Db;
};

export type RunResult = {
  rowCount: number;
  rows: Record<string, unknown>[];
};

type Params = Record<string, unknown>;

function translate(sql: string, params: unknown[] | Params | undefined) {
  if (params === undefined) return { text: sql, values: [] as unknown[] };

  if (Array.isArray(params)) {
    let index = 0;
    return { text: sql.replace(/\?/g, () => `$${++index}`), values: params };
  }

  const seen = new Map<string, number>();
  const values: unknown[] = [];
  const text = sql.replace(/@([A-Za-z_][A-Za-z0-9_]*)/g, (_match, name: string) => {
    const found = seen.get(name);
    if (found !== undefined) return `$${found}`;
    values.push(params[name] ?? null);
    const index = values.length;
    seen.set(name, index);
    return `$${index}`;
  });
  return { text, values };
}

function normalize(row: Record<string, unknown>) {
  const out: Record<string, unknown> = {};
  for (const [key, value] of Object.entries(row)) {
    out[key] = value instanceof Date ? value.toISOString() : value;
  }
  return out;
}

type Executor = Pick<Pool, "query"> | Pick<PoolClient, "query">;

type Statement<Args extends unknown[], R> = {
  get(...args: [...Args] | [Params]): Promise<R | undefined>;
  all(...args: [...Args] | [Params]): Promise<R[]>;
  run(...args: [...Args] | [Params]): Promise<RunResult>;
};

export type Db = {
  prepare<Args extends unknown[] = unknown[], R = Record<string, unknown>>(
    sql: string,
  ): Statement<Args, R>;
  transaction<T>(fn: (db: Db) => Promise<T>): Promise<T>;
};

function makeDb(executor: Executor): Db {
  const db: Db = {
    prepare(sql) {
      const send = async (params: unknown[] | Params | undefined) => {
        const { text, values } = translate(sql, params);
        return executor.query(text, values);
      };

      return {
        async get(params?: unknown[] | Params) {
          const result = await send(params);
          return result.rows[0] ? normalize(result.rows[0]) : undefined;
        },
        async all(params?: unknown[] | Params) {
          const result = await send(params);
          return result.rows.map(normalize);
        },
        async run(params?: unknown[] | Params) {
          const result = await send(params);
          return { rowCount: result.rowCount ?? 0, rows: result.rows.map(normalize) };
        },
      } as never;
    },

    async transaction(fn) {
      const pool = getPool();
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const result = await fn(makeDb(client));
        await client.query("COMMIT");
        return result;
      } catch (error) {
        await client.query("ROLLBACK").catch(() => undefined);
        throw error;
      } finally {
        client.release();
      }
    },
  };
  return db;
}

function getPool(): Pool {
  const scope = globalThis as GlobalWithPool;
  if (!scope.__deixaAquiPool) {
    const connectionString = process.env.DATABASE_URL;
    if (!connectionString) {
      throw new Error("DATABASE_URL nao configurada: o app depende do Postgres do Neon");
    }
    scope.__deixaAquiPool = new Pool({
      connectionString,
      max: POOL_MAX,
      idleTimeoutMillis: 10_000,
    });
  }
  return scope.__deixaAquiPool;
}

function columnExists(executor: Executor, table: string, column: string) {
  return executor
    .query(
      `SELECT 1 FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = $1 AND column_name = $2`,
      [table, column],
    )
    .then((result) => result.rowCount !== 0);
}

async function migrate(executor: Executor) {
  const additions: [string, string, string][] = [
    ["gifts", "total_quantity", "integer NOT NULL DEFAULT 1"],
    ["gifts", "sold_quantity", "integer NOT NULL DEFAULT 0"],
    ["payments", "oversold", "integer NOT NULL DEFAULT 0"],
  ];
  for (const [table, column, definition] of additions) {
    if (!(await columnExists(executor, table, column))) {
      await executor.query(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`);
    }
  }
}

