async function seed(executor: Executor) {
  const gifts: string[] = [];
  const values: unknown[] = [];
  SEED_GIFTS.forEach((gift, index) => {
    values.push(
      gift.slug,
      gift.name,
      gift.description,
      gift.image_key,
      gift.amount_cents,
      gift.category,
      (index + 1) * 10,
      gift.total_quantity ?? 1,
    );
    const base = values.length - 8;
    gifts.push(
      `($${base + 1}, $${base + 2}, $${base + 3}, $${base + 4}, $${base + 5}, $${base + 6}, $${base + 7}, $${base + 8})`,
    );
  });
  await executor.query(
    `INSERT INTO gifts
       (slug, name, description, image_key, amount_cents, category, display_order, total_quantity)
     VALUES ${gifts.join(", ")}
     ON CONFLICT (slug) DO NOTHING`,
    values,
  );

  const settings = Object.entries(SEED_SETTINGS);
  if (settings.length > 0) {
    const rows: string[] = [];
    const params: unknown[] = [];
    settings.forEach(([key, value], index) => {
      params.push(key, value);
      rows.push(`($${index * 2 + 1}, $${index * 2 + 2})`);
    });
    await executor.query(
      `INSERT INTO settings (key, value) VALUES ${rows.join(", ")}
       ON CONFLICT (key) DO NOTHING`,
      params,
    );
  }
}

function ready(): Promise<void> {
  const scope = globalThis as GlobalWithPool;
  if (!scope.__deixaAquiReady) {
    scope.__deixaAquiReady = (async () => {
      const executor = getPool();
      await executor.query(SCHEMA);
      await migrate(executor);
      await seed(executor);
    })().catch((error) => {
      scope.__deixaAquiReady = undefined;
      throw error;
    });
  }
  return scope.__deixaAquiReady;
}

export function getDb(): Db {
  const scope = globalThis as GlobalWithPool;
  if (!scope.__deixaAquiDb) {
    const db = makeDb({
      query: (text: string, values?: unknown[]) => {
        const pending = ready().then(() => getPool().query(text, values as never[]));
        return pending as never;
      },
    } as Executor);
    scope.__deixaAquiDb = db;
  }
  return scope.__deixaAquiDb!;
}